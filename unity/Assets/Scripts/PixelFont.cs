        static int GlyphWidth(char c) =>
            c == ' ' ? SpaceWidth - 1 : Glyphs.TryGetValue(c, out var g) ? g[0].Length : SpaceWidth - 1;

        /// Width of `text` in font pixels.
        public static int WidthCells(string text)
        {
            int width = 0;
            foreach (char c in text) width += GlyphWidth(c) + 1;
            return Mathf.Max(0, width - 1);
        }

        public static float Width(string text, float cell) => WidthCells(text.ToUpperInvariant()) * cell;

        /// The lit pixels of `text` (already upper case), each `cell` across,
        /// with the top left of the text at (left, top).
        public static void Cells(string text, float left, float top, float cell, List<Rect> into)
        {
            int x = 0;
            foreach (char c in text)
            {
                if (Glyphs.TryGetValue(c, out var rows))
                {
                    for (int r = 0; r < Rows; r++)
                        for (int k = 0; k < rows[r].Length; k++)
                            if (rows[r][k] == '#') into.Add(new Rect(left + (x + k) * cell, top + r * cell, cell, cell));
                }
                x += GlyphWidth(c) + 1;
            }
        }
    }
