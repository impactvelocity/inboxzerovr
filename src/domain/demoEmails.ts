import type { Message } from './types';

/** All demo content is fictional. Timestamps are fixed so the demo is deterministic. */

function msg(
  id: string,
  senderName: string,
  senderEmail: string,
  subject: string,
  preview: string,
  bodyText: string,
  receivedAt: string,
  extra: Partial<Message> = {},
): Message {
  return {
    id,
    senderName,
    senderEmail,
    subject,
    preview,
    bodyText,
    receivedAt,
    attachmentMetadata: [],
    originalProviderLabels: ['INBOX'],
    threadId: `thread-${id}`,
    ...extra,
  };
}

