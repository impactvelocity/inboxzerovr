function glyphWidth(c: string): number {
  if (c === ' ') return SpaceWidth - 1;
  const g = Glyphs[c];
  return g !== undefined ? g[0].length : SpaceWidth - 1;
}

/** Width of `text` in font pixels. */
export function widthCells(text: string): number {
  let width = 0;
  for (const c of text) width += glyphWidth(c) + 1;
  return Math.max(0, width - 1);
}

/** Width of `text` at `cell` canvas pixels per font pixel. */
export function width(text: string, cell: number): number {
  return widthCells(text.toUpperCase()) * cell;
}

/**
 * The lit pixels of `text` (already upper case), each `cell` across, with the top left of the
 * text at (left, top). Calls `lit(x, y, w, h)` once per lit pixel.
 */
export function cells(text: string, left: number, top: number, cell: number, lit: (x: number, y: number, w: number, h: number) => void): void {
  let x = 0;
  for (const c of text) {
    const rows = Glyphs[c];
    if (rows !== undefined) {
      for (let r = 0; r < Rows; r++) {
        const row = rows[r];
        for (let k = 0; k < row.length; k++) {
          if (row[k] === '#') lit(left + (x + k) * cell, top + r * cell, cell, cell);
        }
      }
    }
    x += glyphWidth(c) + 1;
  }
}
